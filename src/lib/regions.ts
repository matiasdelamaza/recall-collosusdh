/** Regiones de Chile (orden norte → sur). */
export const CHILE_REGIONS = [
  "Arica y Parinacota",
  "Tarapacá",
  "Antofagasta",
  "Atacama",
  "Coquimbo",
  "Valparaíso",
  "Metropolitana de Santiago",
  "Libertador General Bernardo O'Higgins",
  "Maule",
  "Ñuble",
  "Biobío",
  "La Araucanía",
  "Los Ríos",
  "Los Lagos",
  "Aysén del General Carlos Ibáñez del Campo",
  "Magallanes y de la Antártica Chilena",
] as const;

export type ChileRegion = (typeof CHILE_REGIONS)[number];

export function isChileRegion(value: string): value is ChileRegion {
  return (CHILE_REGIONS as readonly string[]).includes(value);
}
